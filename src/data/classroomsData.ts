export function getAllClassroomStudents(): ClassroomStudent[] {
  const students: ClassroomStudent[] = [];
  mockClassrooms.forEach((room) => {
    room.sections.forEach((sec) => {
      students.push(...sec.students);
    });
  });
  return students;
}

export function getClassroomStats() {
  const all = getAllClassroomStudents();
  const nakThamStudents = all.filter((s) => s.courseType === "นักธรรม");
  const paliStudents = all.filter((s) => s.courseType === "บาลีสนามหลวง");
  
  // Calculate distinct student names
  const uniqueNames = new Set(all.map((s) => s.name));
  
  return {
    totalRooms: mockClassrooms.length,
    totalNakThamEnrollments: nakThamStudents.length,
    totalPaliEnrollments: paliStudents.length,
    uniqueStudentsCount: uniqueNames.size,
    ageDistribution: all.reduce((acc, curr) => {
      const group = curr.age < 10 ? "ต่ำกว่า 10 ปี" : curr.age <= 15 ? "10 - 15 ปี" : "16 ปีขึ้นไป";
      acc[group] = (acc[group] || 0) + 1;
      return acc;
    }, {} as Record<string, number>),
  };
}
