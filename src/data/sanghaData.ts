  const totalMonks = officialMonksList.length;
  const totalNovices = officialNovicesList.length;
  const totalSangha = totalMonks + totalNovices;
  const internationalNovices = officialNovicesList.filter(n => n.country !== "ไทย").length;
  const thaiNovices = officialNovicesList.filter(n => n.country === "ไทย").length;
  const healthyNovices = officialNovicesList.filter(n => n.healthStatus === "HEALTHY").length;
