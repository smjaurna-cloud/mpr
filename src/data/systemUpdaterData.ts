/**
 * Check whether a given admin persona has permission to update a given module
 */
export function checkModulePermission(admin: AdminPersona, moduleId: string): boolean {
  if (admin.isSuperAdmin || admin.role === "SUPER_ADMIN") return true;
  return admin.assignedModuleIds.includes(moduleId);
}

